    public function checkForValidInvoiceNumberAndDate(Invoice $invoice): bool
    {
        if (!$invoice->getNumber() || !$invoice->getType()) {
            return false;
        }

        $repo = $this->em->getRepository(Invoice::class);

        $previousInvoice = $repo->getPreviousInvoiceByNumberAndType(
            $invoice->getNumber(),
            $invoice->getType()
        );

        $nextInvoice = $repo->getNextInvoiceByNumberAndType(
            $invoice->getNumber(),
            $invoice->getType()
        );

        $issueDate = $invoice->getIssueDate();

        if (!$issueDate) {
            return false;
        }

        // No neighbors → always valid
        if ($previousInvoice === null && $nextInvoice === null) {
            return true;
        }

        // Valid only if date is between neighbors
        if (
            ($previousInvoice === null || $previousInvoice->getIssueDate() <= $issueDate)
            &&
            ($nextInvoice === null || $issueDate <= $nextInvoice->getIssueDate())
        ) {
            return true;
        }

        return false;
    }

    public function setValidNumberAndDateByKind(Invoice $invoice): void
    {
        //
        // 1. Automatically set required dates if not provided
        //
        $now = new \DateTimeImmutable();

        if ($invoice->getIssueDate() === null) {
            $invoice->setIssueDate($now);
        }

        if ($invoice->getTaxDate() === null) {
            $invoice->setTaxDate($invoice->getIssueDate());
        }

        if ($invoice->getCreatedAt() === null) {
            $invoice->setCreatedAt($now);
        }

        //
        // 2. If number already provided → validate uniqueness only
        //
        if ($invoice->getNumber() !== null && $invoice->getNumber() !== '') {

            $existing = $this->em
                ->getRepository(Invoice::class)
                ->findOneBy([
                    'type' => $invoice->getType(),
                    'number' => $invoice->getNumber(),
                ]);

            if ($existing && $existing->getId() !== $invoice->getId()) {
                throw new \RuntimeException(
                    sprintf(
                        'Number "%s" already exists for "%s".',
                        $invoice->getNumber(),
                        $invoice->getType()->label()
                    )
                );
            }

            return; // number is manually set → done
        }

        //
        // 3. Auto-generate the next number for this type
        //
        $nextNumber = $this->getNextNumberForType($invoice->getType());
        $invoice->setNumber($nextNumber);
    }

    private function getNextNumberForType(InvoiceType $type): int
    {
        $qb = $this->em->createQueryBuilder();

        $qb->select('MAX(i.number)')
            ->from(Invoice::class, 'i')
            ->where('i.type = :type')
            ->setParameter('type', $type->value);

        $max = $qb->getQuery()->getSingleScalarResult();

        return $max ? ((int)$max + 1) : 1;
    }

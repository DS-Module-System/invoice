    public function getTextByVersion1(Invoice $invoice): string
    {
        $text = '1';
        if ($invoice->getType() == InvoiceType::Invoice) {
            $text .= '#1';
        } elseif ($invoice->getType() == InvoiceType::CreditInvoice) {
            $text .= '#2';
        } elseif ($invoice->getType() == InvoiceType::DebitInvoice) {
            $text .= '#3';
        } else {
            $text .= '#NA';
        }

        $text .= '#' . $invoice->getNumber();
        $text .= '#1';

        $companySettings = $this->em->getRepository(Setting::class)->findOneBy(['property' => 'company_info']);

        if ($companySettings->getValue()['eek']) {
            $text .= '|BG|' . $companySettings->getValue()['eek'];
        } else {
            $text .= '#NA';
        }

        $invoiceClient = $invoice->getClient();

        if ($invoiceClient instanceof Client) {
            $text .= '#1';
            if ($invoiceClient->getEek()) {
                $text .= '|BG|' . $invoiceClient->getEek();
            } else {
                $text .= '#NA';
            }
        }

        $text .= '#' . $invoice->getIssueDate()->format('Y-m-d');

        $text .= '#' . $invoice->getDdsPrice();
        $text .= '#' . $invoice->getTotalPrice();

        if ($invoice->getPaymentMethod() === InvoicePaymentMethod::Bank) {
            $text .= '#1';
        } else {
            $text .= '#NA';
        }
        $text .= '#BGN';


        return $text;
    }

